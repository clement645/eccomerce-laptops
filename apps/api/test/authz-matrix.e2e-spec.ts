import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { RequestMethod } from '@nestjs/common';
import { GUARDS_METADATA, METHOD_METADATA, PATH_METADATA } from '@nestjs/common/constants.js';
import { MetadataScanner, ModulesContainer, Reflector } from '@nestjs/core';
import type { NestExpressApplication } from '@nestjs/platform-express';
import { PERMISSIONS, type Permission } from '@repo/shared-types';
import request from 'supertest';
import { RedisService } from '../src/infrastructure/redis/redis.service.js';
import { TokenService } from '../src/modules/auth/token.service.js';
import {
  AUTH_METADATA,
  COOKIE_REQUEST_METADATA,
  type AuthRequirements,
} from '../src/modules/auth/guards/auth.decorators.js';
import { OptionalAuthGuard } from '../src/modules/auth/guards/optional-auth.guard.js';
import {
  RATE_LIMIT_METADATA,
  type RateLimitRule,
} from '../src/common/rate-limit/rate-limit.decorator.js';
import { removeStaff, staffWithSession } from './support/staff.js';
import { createTestApp } from './support/test-app.js';

const MATRIX_FILE = fileURLToPath(new URL('../../../docs/AUTHZ-MATRIX.md', import.meta.url));
const run = `authz${Date.now()}`;

interface RouteInfo {
  method: string;
  path: string;
  access: 'admin' | 'customer' | 'optional customer' | 'public';
  permissions: Permission[];
  cookie: string | null;
  rateLimits: string[];
}

/** Public endpoints under /admin: sign-in steps and invitation links. Anything else there needs a staff session. */
const PUBLIC_ADMIN_ROUTES = new Set([
  'POST /admin/auth/login',
  'POST /admin/auth/mfa/setup',
  'POST /admin/auth/mfa/verify',
  'POST /admin/auth/refresh',
  'POST /admin/auth/logout',
  'POST /admin/auth/set-password',
]);

/** Every controller route with the access rules declared on it. */
function collectRoutes(app: NestExpressApplication): RouteInfo[] {
  const scanner = new MetadataScanner();
  const reflector = app.get(Reflector);
  const routes: RouteInfo[] = [];
  const controllers = [...app.get(ModulesContainer).values()].flatMap((m) => [
    ...m.controllers.values(),
  ]);
  for (const wrapper of controllers) {
    const { instance, metatype } = wrapper;
    if (!instance || !metatype) continue;
    const base = (Reflect.getMetadata(PATH_METADATA, metatype) as string | undefined) ?? '';
    const prototype = Object.getPrototypeOf(instance) as Record<string, unknown>;
    for (const name of scanner.getAllMethodNames(prototype)) {
      const handler = prototype[name] as object;
      const sub = Reflect.getMetadata(PATH_METADATA, handler) as string | undefined;
      if (sub === undefined) continue;
      const method = RequestMethod[Reflect.getMetadata(METHOD_METADATA, handler) as RequestMethod];
      const path =
        `/${[base, sub].filter(Boolean).join('/')}`.replace(/\/+/g, '/').replace(/\/$/, '') || '/';
      const auth = reflector.getAllAndOverride<AuthRequirements | undefined>(AUTH_METADATA, [
        handler as () => void,
        metatype as () => void,
      ]);
      const guards = [
        ...((Reflect.getMetadata(GUARDS_METADATA, handler) as unknown[]) ?? []),
        ...((Reflect.getMetadata(GUARDS_METADATA, metatype) as unknown[]) ?? []),
      ];
      const rules = [
        ...((Reflect.getMetadata(RATE_LIMIT_METADATA, metatype) as RateLimitRule[]) ?? []),
        ...((Reflect.getMetadata(RATE_LIMIT_METADATA, handler) as RateLimitRule[]) ?? []),
      ];
      routes.push({
        method,
        path,
        access: auth
          ? auth.audience === 'admin'
            ? 'admin'
            : 'customer'
          : guards.includes(OptionalAuthGuard)
            ? 'optional customer'
            : 'public',
        permissions: auth?.permissions ?? [],
        cookie:
          (Reflect.getMetadata(COOKIE_REQUEST_METADATA, handler) as string | undefined) ??
          (Reflect.getMetadata(COOKIE_REQUEST_METADATA, metatype) as string | undefined) ??
          null,
        rateLimits: rules.map(
          (r) => `${r.name} ${r.limit}/${r.windowSeconds}s${r.failClosed ? ' (fails closed)' : ''}`,
        ),
      });
    }
  }
  return routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

function renderMatrix(routes: RouteInfo[]): string {
  const rows = routes.map((r) => {
    const who =
      r.access === 'admin'
        ? `staff${r.permissions.length ? `: ${r.permissions.map((p) => `\`${p}\``).join(', ')}` : ' (any)'}`
        : r.access;
    return `| ${r.method} | \`/api/v1${r.path}\` | ${who} | ${r.cookie ? `${r.cookie} cookie + CSRF check` : ''} | ${r.rateLimits.join('; ')} |`;
  });
  return [
    '# Authorization matrix',
    '',
    'Generated by `apps/api/test/authz-matrix.e2e-spec.ts` from the routes the API actually registers. The test fails',
    'when a route is added, removed or its protection changes without this file being updated, so every change',
    'to access control is reviewed. Regenerate with `UPDATE_AUTHZ_MATRIX=1 pnpm --filter @repo/api test:e2e`.',
    '',
    'All routes also share the global per-IP limit (`RATE_LIMIT_PER_MINUTE`). "staff" means a signed-in staff',
    'member with completed two-factor authentication; "customer" means a signed-in storefront customer.',
    '',
    '| Method | Path | Who | Cookie | Extra rate limits |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

/** Fills route parameters with harmless values of the right shape. */
function concrete(path: string): string {
  return path
    .replace(':orderNumber', 'EL-2026-000001')
    .replace(':slug', 'no-such-product')
    .replace(':key', 'store.profile')
    .replace(':secret', 'x'.repeat(32))
    .replace(/:[A-Za-z]+/g, () => randomUUID());
}

describe('Authorization matrix (e2e)', () => {
  let app: NestExpressApplication;
  let routes: RouteInfo[];
  const http = () => request(app.getHttpServer());

  beforeAll(async () => {
    app = await createTestApp();
    routes = collectRoutes(app);
  });

  beforeEach(async () => {
    const redis = app.get(RedisService).client;
    const keys = await redis.keys('ecommerce-test:ratelimit:*');
    if (keys.length) await redis.del(...keys);
  });

  afterAll(async () => {
    await removeStaff(app, run);
    await app.close();
  });

  it('matches the reviewed matrix in docs/AUTHZ-MATRIX.md', () => {
    const rendered = renderMatrix(routes);
    if (process.env.UPDATE_AUTHZ_MATRIX === '1') writeFileSync(MATRIX_FILE, rendered);
    let committed = '';
    try {
      committed = readFileSync(MATRIX_FILE, 'utf8');
    } catch {
      // Missing file fails below with a helpful diff.
    }
    expect(
      committed,
      'Route protection changed. Review it, then regenerate docs/AUTHZ-MATRIX.md',
    ).toBe(rendered);
  });

  it('protects every admin route with a staff session, except the sign-in steps', () => {
    const unprotected = routes
      .filter((r) => r.path.startsWith('/admin') && r.access !== 'admin')
      .map((r) => `${r.method} ${r.path}`)
      .filter((r) => !PUBLIC_ADMIN_ROUTES.has(r));
    expect(unprotected).toEqual([]);
  });

  it('protects every customer account route', () => {
    const open = routes
      .filter((r) => r.path.startsWith('/account') && r.access !== 'customer')
      .map((r) => `${r.method} ${r.path}`);
    expect(open).toEqual([]);
  });

  it('never accepts a token meant for the other app', () => {
    // Admin and storefront tokens differ only in audience; each guard checks it.
    const admin = routes.filter((r) => r.access === 'admin').length;
    const customer = routes.filter((r) => r.access === 'customer').length;
    expect(admin).toBeGreaterThan(40);
    expect(customer).toBeGreaterThan(10);
  });

  it('refuses every protected route without a session, with the wrong audience, and without the permission', async () => {
    const tokens = app.get(TokenService);
    const customerToken = await tokens.signAccess({
      userId: randomUUID(),
      sessionId: randomUUID(),
      audience: 'storefront',
    });
    // A real, MFA-verified staff session that holds every permission except the one being tested.
    const failures: string[] = [];
    const cache = new Map<string, string>();
    const staffWithout = async (missing: Permission[]) => {
      const key = missing.join(',');
      if (!cache.has(key)) {
        const member = await staffWithSession(
          app,
          `${run}-${cache.size}@example.com`,
          PERMISSIONS.filter((p) => !missing.includes(p)),
        );
        cache.set(key, member.token);
      }
      return cache.get(key)!;
    };

    for (const route of routes.filter((r) => r.access === 'admin' || r.access === 'customer')) {
      const path = `/api/v1${concrete(route.path)}`;
      const call = (token?: string) => {
        const req = http()[route.method.toLowerCase() as 'get'](path);
        if (token) req.set('Authorization', `Bearer ${token}`);
        return req.send({});
      };
      const label = `${route.method} ${route.path}`;
      if ((await call()).status !== 401) failures.push(`${label}: no token was not 401`);
      if (route.access === 'admin') {
        if ((await call(customerToken)).status !== 401)
          failures.push(`${label}: customer token was not 401`);
        if (route.permissions.length) {
          const status = (await call(await staffWithout(route.permissions))).status;
          if (status !== 403)
            failures.push(`${label}: staff without ${route.permissions.join('+')} got ${status}`);
        }
      }
    }
    expect(failures).toEqual([]);
  }, 120_000);
});
